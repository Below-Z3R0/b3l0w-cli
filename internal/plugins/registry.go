//go:embed plugins.json
var embedded []byte

// Embedded devuelve el manifiesto compilado.
func Embedded() []byte { return embedded }

// LoadDefault carga el manifiesto con la jerarquía del registry.
func LoadDefault() (*Manifest, error) {
	data, _, err := registry.Load(registry.Plugins, embedded)
	if err != nil {
		return nil, err
	}
	return parse(data)
}

// DistributionRepo es el repo único que publica todos los plugins.
const DistributionRepo = "Below-Z3R0/b3l0w-plugins"

// SupportedPluginAPI es el plugin_api máximo que este CLI acepta.
// Se sube cuando el shell sube el suyo.
const SupportedPluginAPI = 43

// Entry es un plugin del manifiesto de distribución.
type Entry struct {
	ID        string `json:"id"`
	Name      string `json:"name"`
	Repo      string `json:"repo"`
	Path      string `json:"path"`
	Version   string `json:"version"`
	PluginAPI int    `json:"plugin_api"`
	SHA256    string `json:"sha256,omitempty"`
}

// Manifest es plugins/plugins.json del repo b3l0w.
type Manifest struct {
	Version int     `json:"version"`
	Plugins []Entry `json:"plugins"`
}

// LoadManifest lee el manifiesto.
func LoadManifest(path string) (*Manifest, error) {
	// Sin path explícito, la fuente es el registry.
	if path == "" {
		return LoadDefault()
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	return parse(data)
}

func parse(data []byte) (*Manifest, error) {
	var m Manifest
	if err := json.Unmarshal(data, &m); err != nil {
		return nil, err
	}
	if m.Version == 0 || len(m.Plugins) == 0 {
		return nil, fmt.Errorf("manifiesto de plugins vacío o sin versión")
	}
	return &m, nil
}

// SaveManifest lo escribe ordenado por id.
func SaveManifest(path string, m *Manifest) error {
	sort.Slice(m.Plugins, func(i, j int) bool { return m.Plugins[i].ID < m.Plugins[j].ID })
	data, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, append(data, '\n'), 0o644)
}

// slug es el nombre de carpeta que espera Noctalia: la parte después
// de la barra del id ("b3l0w/wallpaper" -> "wallpaper").
func slug(e Entry) string {
	if i := strings.LastIndex(e.ID, "/"); i >= 0 && i+1 < len(e.ID) {
		return e.ID[i+1:]
	}
	return e.Path
}

// Collect lee todas las carpetas de plugin del repo único. La carpeta
// manda: debe llamarse igual que el slug del id, porque Noctalia
// indexa por nombre de directorio.
func Collect(registryDir string) ([]Entry, error) {
	dirs, err := os.ReadDir(registryDir)
	if err != nil {
		return nil, err
	}
	var out []Entry
	for _, de := range dirs {
		if !de.IsDir() || strings.HasPrefix(de.Name(), ".") {
			continue
		}
		name := de.Name()
		pluginToml := filepath.Join(registryDir, name, "plugin.toml")
		if _, err := os.Stat(pluginToml); err != nil {
			continue
		}
		meta, err := readPluginMeta(pluginToml)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", name, err)
		}
		if meta.Name == "" {
			return nil, fmt.Errorf("%s: plugin.toml sin name", name)
		}
		if !strings.HasSuffix(meta.ID, "/"+name) {
			return nil, fmt.Errorf("%s: el id %q no termina en /%s", name, meta.ID, name)
		}
		if meta.PluginAPI < 1 {
			return nil, fmt.Errorf("%s: plugin_api inválido (%d)", meta.ID, meta.PluginAPI)
		}
		out = append(out, Entry{
			ID:        meta.ID,
			Name:      meta.Name,
			Repo:      DistributionRepo,
			Path:      name,
			Version:   meta.Version,
			PluginAPI: meta.PluginAPI,
		})
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("no hay plugins en %s", registryDir)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].ID < out[j].ID })
	return out, nil
}

// RenderCatalog genera el catalog.toml de Noctalia. Las fechas salen
// del historial del repo único, por carpeta de plugin.
func RenderCatalog(registryDir string, entries []Entry) (string, error) {
	var b strings.Builder
	b.WriteString("# This file is auto-generated by `b3l0w plugins build`.\n")
	b.WriteString("# Do not edit manually.\n\n")

	// Fallback cuando el plugin no esta en un repo git: se usa el
	// timestamp del archivo mas nuevo del plugin, no el reloj. Con
	// time.Now() cada render daba un valor distinto y el catalogo
	// recien generado nunca coincidia consigo mismo (CheckCatalog
	// daba false al segundo).
	for _, entry := range entries {
		meta, err := readPluginMeta(filepath.Join(registryDir, entry.Path, "plugin.toml"))
		if err != nil {
			return "", fmt.Errorf("%s: %w", entry.ID, err)
		}
		if meta.ID != entry.ID {
			return "", fmt.Errorf("%s: el manifiesto dice %s y plugin.toml dice %s", entry.Path, entry.ID, meta.ID)
		}
		updated := gitTimestamp(registryDir, entry.Path, false)
		added := gitTimestamp(registryDir, entry.Path, true)
		if updated == 0 {
			updated = fileTimestamp(filepath.Join(registryDir, entry.Path))
		}
		if added == 0 {
			added = updated
		}
		fmt.Fprintf(&b, "[[plugin]]\n")
		fmt.Fprintf(&b, "id = %q\n", meta.ID)
		fmt.Fprintf(&b, "name = %q\n", meta.Name)
		fmt.Fprintf(&b, "version = %q\n", meta.Version)
		fmt.Fprintf(&b, "updated_at = %d\n", updated)
		fmt.Fprintf(&b, "added_at = %d\n", added)
		fmt.Fprintf(&b, "author = %q\n", meta.Author)
		fmt.Fprintf(&b, "license = %q\n", meta.License)
		fmt.Fprintf(&b, "icon = %q\n", meta.Icon)
		fmt.Fprintf(&b, "description = %q\n", meta.Description)
		fmt.Fprintf(&b, "plugin_api = %d\n", meta.PluginAPI)
		if len(meta.Tags) > 0 {
			fmt.Fprintf(&b, "tags = [%s]\n", quoteList(meta.Tags))
		} else {
			b.WriteString("tags = []\n")
		}
		b.WriteString("\n")
	}
	return b.String(), nil
}

// Build escribe catalog.toml y, si manifestPath no está vacío,
// regenera plugins.json desde el mismo conjunto.
func Build(registryDir, manifestPath string, entries []Entry) error {
	catalog, err := RenderCatalog(registryDir, entries)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(registryDir, "catalog.toml"), []byte(catalog), 0o644); err != nil {
		return err
	}
	if manifestPath == "" {
		return nil
	}
	return SaveManifest(manifestPath, &Manifest{Version: 1, Plugins: entries})
}

// CheckCatalog dice si catalog.toml ya coincide con lo que generaría
// build. Un false es un catálogo desactualizado.
func CheckCatalog(registryDir string, entries []Entry) (bool, error) {
	want, err := RenderCatalog(registryDir, entries)
	if err != nil {
		return false, err
	}
	got, err := os.ReadFile(filepath.Join(registryDir, "catalog.toml"))
	if os.IsNotExist(err) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	return string(got) == want, nil
}

// DefaultPluginsDir es donde Noctalia guarda los plugins locales.
func DefaultPluginsDir() string {
	home, err := os.UserHomeDir()
	if err != nil {
		return ""
	}
	return filepath.Join(home, ".local", "share", "noctalia", "plugins")
}

// DefaultManifestPath es plugins/plugins.json del repo de distribución.
func DefaultManifestPath() string {
	home, err := os.UserHomeDir()
	if err != nil {
		return ""
	}
	return filepath.Join(home, "Documents", "Github", "b3l0w", "plugins", "plugins.json")
}

// Dependencies devuelve las dependencias declaradas por cada plugin
// instalado o materializado.
func Dependencies() (map[string][]string, error) {
	m, err := LoadDefault()
	if err != nil {
		return nil, err
	}
	out := make(map[string][]string)
	for _, entry := range m.Plugins {
		for _, dir := range candidateDirs(DefaultPluginsDir(), entry) {
			meta, err := readPluginMeta(filepath.Join(dir, "plugin.toml"))
			if err == nil {
				out[entry.ID] = meta.Dependencies
				break
			}
		}
	}
	return out, nil
}

type pluginMeta struct {
	ID           string
	Name         string
	Version      string
	PluginAPI    int
	Author       string
	License      string
	Icon         string
	Description  string
	Tags         []string
	Dependencies []string
}

var (
	reString = func(key string) *regexp.Regexp {
		return regexp.MustCompile(`(?m)^` + key + `\s*=\s*"([^"]*)"`)
	}
	reInt = func(key string) *regexp.Regexp {
		return regexp.MustCompile(`(?m)^` + key + `\s*=\s*(\d+)`)
	}
	reTags = regexp.MustCompile(`(?m)^tags\s*=\s*\[([^\]]*)\]`)
	reDeps = regexp.MustCompile(`(?m)^dependencies\s*=\s*\[([^\]]*)\]`)
)

func readPluginMeta(path string) (pluginMeta, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return pluginMeta{}, err
	}
	return parsePluginMeta(string(data))
}

func parsePluginMeta(text string) (pluginMeta, error) {
	meta := pluginMeta{}
	if mm := reString("id").FindStringSubmatch(text); mm != nil {
		meta.ID = mm[1]
	}
	if mm := reString("name").FindStringSubmatch(text); mm != nil {
		meta.Name = mm[1]
	}
	if mm := reString("version").FindStringSubmatch(text); mm != nil {
		meta.Version = mm[1]
	}
	if mm := reInt("plugin_api").FindStringSubmatch(text); mm != nil {
		meta.PluginAPI, _ = strconv.Atoi(mm[1])
	}
	if mm := reString("author").FindStringSubmatch(text); mm != nil {
		meta.Author = mm[1]
	}
	if mm := reString("license").FindStringSubmatch(text); mm != nil {
		meta.License = mm[1]
	}
	if mm := reString("icon").FindStringSubmatch(text); mm != nil {
		meta.Icon = mm[1]
	}
	if mm := reString("description").FindStringSubmatch(text); mm != nil {
		meta.Description = mm[1]
	}
	if mm := reTags.FindStringSubmatch(text); mm != nil {
		for _, tag := range strings.Split(mm[1], ",") {
			tag = strings.Trim(strings.TrimSpace(tag), `"`)
			if tag != "" {
				meta.Tags = append(meta.Tags, tag)
			}
		}
	}
	if mm := reDeps.FindStringSubmatch(text); mm != nil {
		for _, dep := range strings.Split(mm[1], ",") {
			dep = strings.Trim(strings.TrimSpace(dep), `"`)
			if dep != "" {
				meta.Dependencies = append(meta.Dependencies, dep)
			}
		}
	}
	if meta.ID == "" || meta.Version == "" {
		return meta, fmt.Errorf("plugin.toml sin id o version")
	}
	return meta, nil
}

// gitTimestamp devuelve la fecha (epoch) del último commit que tocó el
// plugin, o del primero si first=true. 0 si no hay historial.
func gitTimestamp(repoDir, pluginSlug string, first bool) int64 {
	args := []string{"-C", repoDir, "log", "-1", "--format=%ct", "--", pluginSlug}
	if first {
		args = []string{"-C", repoDir, "log", "--reverse", "--format=%ct", "--", pluginSlug}
	}
	out, err := system.Run("git", args...)
	if err != nil {
		return 0
	}
	lines := strings.Split(strings.TrimSpace(out), "\n")
	if len(lines) == 0 || lines[0] == "" {
		return 0
	}
	n, err := strconv.ParseInt(strings.TrimSpace(lines[0]), 10, 64)
	if err != nil {
		return 0
	}
	return n
}

// fileTimestamp devuelve el mtime mas reciente de un arbol de archivos.
// Es el fallback cuando el plugin no esta en un repo git: tiene que ser
// estable entre llamadas, asi que no puede ser el reloj.
func fileTimestamp(dir string) int64 {
	var newest int64
	filepath.Walk(dir, func(path string, info os.FileInfo, err error) error {
		if err != nil || info == nil || info.IsDir() {
			return nil
		}
		if m := info.ModTime().Unix(); m > newest {
			newest = m
		}
		return nil
	})
	return newest
}

func quoteList(items []string) string {
	out := make([]string, len(items))
	for i, item := range items {
		out[i] = strconv.Quote(item)
	}
	return strings.Join(out, ", ")
}
